#!/usr/bin/env python3
"""Generate differential golden vectors with cantools as an independent oracle.

Spec section 15.1 wants a reference implementation that is not ours, and
section 15.5 wants the fixtures stored with their seed so a disagreement is
reproducible. This script is run by a developer, not by CTest: the generated
file is committed, so the C++ suite needs no Python and no cantools at test
time (research R-20).

Output format is one line per case rather than the JSON of section 15.5:

    <can-id> <extended 0|1> <payload-hex> <signal>=<physical> ...

A line format keeps the comparison test free of a JSON dependency - the test
target links tcu_dbc, which deliberately links nothing at all. The content is
the same; only the punctuation differs.

Usage:
    python3 scripts/generate_dbc_vectors.py --seed 20261106 --count 10000 \
        --dbc configs/virtual_tcu.dbc --out tests/fixtures/dbc/golden/matrix.txt
"""

import argparse
import random
import sys

try:
    import cantools
except ImportError:  # pragma: no cover - the message is the point
    sys.exit("cantools is not installed. Run: python3 -m pip install cantools==39.4.4")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dbc", default="configs/virtual_tcu.dbc")
    parser.add_argument("--out", default="tests/fixtures/dbc/golden/matrix.txt")
    parser.add_argument("--seed", type=int, default=20261106)
    parser.add_argument("--count", type=int, default=10000)
    args = parser.parse_args()

    database = cantools.database.load_file(args.dbc)
    rng = random.Random(args.seed)

    lines = []
    skipped = 0
    for _ in range(args.count):
        message = rng.choice(database.messages)
        payload = bytearray(rng.getrandbits(8) for _ in range(message.length))

        # A random selector byte lands on a branch that does not exist about
        # 99% of the time, and cantools then refuses the frame - which would
        # leave the multiplex path almost uncovered in the matrix. So when the
        # message is multiplexed, the selector is forced onto a declared
        # branch. Narrow on purpose: it only rewrites a byte-aligned, 8-bit
        # little-endian selector, which is what the lab DBC has; anything else
        # falls through to the skip path rather than being guessed at.
        branch_ids = sorted({
            muxed
            for signal in message.signals
            if signal.multiplexer_ids
            for muxed in signal.multiplexer_ids
        })
        selector = next((s for s in message.signals if s.is_multiplexer), None)
        if branch_ids and selector is not None:
            if (selector.length == 8 and selector.start % 8 == 0 and
                    selector.byte_order == "little_endian"):
                payload[selector.start // 8] = rng.choice(branch_ids)
        payload = bytes(payload)
        try:
            # decode_choices=False keeps enums numeric: the comparison is about
            # bits and arithmetic, not about labels.
            decoded = message.decode(payload, decode_choices=False,
                                     allow_truncated=False)
        except Exception:
            # cantools refuses some random payloads (an unknown multiplex
            # selector, for one). A case the oracle will not answer is not a
            # case we can compare, so it is skipped and counted - never guessed.
            skipped += 1
            continue

        fields = []
        for name, value in decoded.items():
            if isinstance(value, (int, float)):
                fields.append("{}={!r}".format(name, float(value)))
        if not fields:
            skipped += 1
            continue

        lines.append("{} {} {} {}".format(
            message.frame_id & 0x1FFFFFFF,
            1 if message.is_extended_frame else 0,
            payload.hex(),
            " ".join(fields),
        ))

    with open(args.out, "w", encoding="utf-8", newline="\n") as out:
        out.write("# generated by scripts/generate_dbc_vectors.py - do not edit by hand\n")
        out.write("# cantools={} seed={} dbc={} requested={} emitted={} skipped={}\n".format(
            cantools.__version__, args.seed, args.dbc, args.count, len(lines), skipped))
        out.write("# intentional divergences (research R-20): cantools accepts\n")
        out.write("#   SIG_VALTYPE_, extended multiplexing and BO_ lengths above 8,\n")
        out.write("#   all of which v1 rejects at load. Those files are not generated here.\n")
        for line in lines:
            out.write(line + "\n")

    print("wrote {} cases to {} (skipped {})".format(len(lines), args.out, skipped))
    return 0


if __name__ == "__main__":
    sys.exit(main())
